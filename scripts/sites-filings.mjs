// For each claim in sites/claims.json, pull the sentences from the company's
// 10-Ks that name the facility, so the claim can be checked in the filing's
// own words. Runs in GitHub Actions (SEC EDGAR is not reachable from every
// sandbox). Writes sites/results/filings.json and filings.md.
//
//   node scripts/sites-filings.mjs [--only id1,id2]

import { parseArgs } from 'node:util';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { tickerMap, submissions, filingUrl, secText } from '../lib/sec.mjs';
import { annualReports, mentions } from '../lib/sites.mjs';

const { values: args } = parseArgs({ options: { only: { type: 'string' } } });
const root = new URL('../sites/', import.meta.url);
let { claims } = JSON.parse(await readFile(new URL('claims.json', root), 'utf8'));
if (args.only) claims = claims.filter(c => args.only.split(',').includes(c.id));

const map = await tickerMap();
const results = [];
for (const c of claims) {
  const entry = map.get(c.ticker);
  if (!entry) { results.push({ id: c.id, error: `no CIK for ${c.ticker}` }); continue; }
  const reports = annualReports(await submissions(entry.cik), c.filing.years);
  const found = [];
  for (const f of reports) {
    const url = filingUrl(entry.cik, f);
    try {
      found.push({ ...f, url, sentences: mentions(await secText(url), c.filing.phrases) });
    } catch (e) { found.push({ ...f, url, error: e.message }); }
  }
  const missing = c.filing.years.filter(y => !reports.some(f => f.year === y));
  results.push({ id: c.id, ticker: c.ticker, filings: found, ...(missing.length && { missing_years: missing }) });
  console.error(`${c.id}: ${found.map(f => `${f.year} ${f.sentences?.length ?? 'error'}`).join(', ')}`);
}

const out = new URL('results/', root);
await mkdir(out, { recursive: true });
await writeFile(new URL('filings.json', out), JSON.stringify({ generated: new Date().toISOString().slice(0, 10), results }, null, 1) + '\n');
const md = ['# What the 10-Ks say', '', 'Sentences from each company\'s annual reports that name the facility. Generated by `scripts/sites-filings.mjs`.', ''];
for (const r of results) {
  const c = claims.find(x => x.id === r.id);
  md.push(`## ${c.company}: ${c.site}`, '', `Our summary: ${c.claim}`, '');
  if (r.error) { md.push(`Error: ${r.error}`, ''); continue; }
  for (const f of r.filings) {
    md.push(`**10-K for ${f.year}** (filed ${f.filed}, [${f.accession}](${f.url}))`, '');
    if (f.error) md.push(`Error: ${f.error}`);
    else if (!f.sentences.length) md.push(`No sentence names ${c.filing.phrases.map(p => `"${p}"`).join(' or ')}.`);
    else for (const s of f.sentences) md.push(`> ${s}`, '');
    md.push('');
  }
  if (r.missing_years) md.push(`No 10-K found for: ${r.missing_years.join(', ')}`, '');
}
await writeFile(new URL('filings.md', out), md.join('\n'));
console.log(md.join('\n'));
